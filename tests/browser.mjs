// Run tests/preview.mjs first. Supply PLAYWRIGHT_MODULE if Playwright is installed outside this checkout.
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {submissionCode, moderationKey, fixturePdf, fixtureQuestions} from './share-fixture.mjs';

const {chromium} = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(resolve(process.env.PLAYWRIGHT_MODULE)).href : 'playwright');
const browser = await chromium.launch({headless: true});
const evidence = resolve(process.env.V3_EVIDENCE || 'work/browser-evidence');
const origin = `http://127.0.0.1:${Number(process.env.V3_PREVIEW_PORT || 39200)}`;
const runtimePort = String(Number(new URL(origin).port) + 1);
const notes = 'Fixture notes stay on device <img src=x onerror=alert(1)>';
const prompt = 'Fixture local prompt only';
const file = (name, text) => ({name, mimeType: 'application/pdf', buffer: Buffer.from(fixturePdf(text))});
const requests = [];
await mkdir(evidence, {recursive:true});

try {
  const first = await browser.newContext({viewport:{width:1440,height:960},acceptDownloads:true});
  const second = await browser.newContext({viewport:{width:768,height:960},acceptDownloads:true});
  const page = await first.newPage(), guest = await second.newPage();
  page.setDefaultTimeout(8_000); guest.setDefaultTimeout(8_000);
  const watch = request => requests.push({url:request.url(),method:request.method(),body:request.postData(),auth:request.headers().authorization});
  page.on('request',watch); guest.on('request',watch);
  const tab = (p,name) => p.getByRole('navigation').getByRole('button',{name,exact:true}).click();
  const status = (p,text) => p.locator('#message').filter({hasText:text}).waitFor();
  await page.goto(origin); await page.getByRole('heading',{name:'私人题库'}).waitFor();
  for (const width of [375,768,1280,1440,1920]) {
    await page.setViewportSize({width,height:960});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, `overflow at ${width}px`);
    await page.screenshot({path:resolve(evidence,`device-${width}.png`)});
  }
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(() => document.activeElement.textContent), '跳到内容');
  await page.locator('#pdfs').setInputFiles([file('0580_s26_qp_11.pdf',fixtureQuestions),file('0580_s26_ms_11.pdf')]);
  await status(page,'保存 2 份 PDF');
  assert.equal(await page.getByText('已配对',{exact:false}).count(),2);
  await tab(page,'搜题');
  await page.getByLabel('题目关键词').fill('probability');
  await page.getByRole('button',{name:'搜索正文'}).click();
  await page.locator('#question-status').filter({hasText:'找到 1 个结果'}).waitFor();
  assert.equal(await page.locator('#question-results li h2').textContent(), 'Question 1(a)');
  assert.equal(await page.locator('#question-results img').count(), 2);
  await tab(page,'私人题库');
  await page.getByRole('button',{name:'笔记与草稿'}).first().click();
  await page.getByLabel('学习笔记').fill(notes);
  await page.getByLabel('练习草稿').fill('Fixture private draft');
  await page.getByRole('button',{name:'保存记录'}).click();
  await status(page,'学习记录已在当前设备保存');
  await page.reload();
  await page.getByRole('button',{name:'笔记与草稿'}).first().click();
  assert.equal(await page.getByLabel('学习笔记').inputValue(),notes);
  assert.equal(await page.locator('img[src=x]').count(),0);
  await guest.goto(origin);
  await guest.getByText('0 份 PDF',{exact:true}).waitFor();
  await tab(page,'数据与备份');
  const download = page.waitForEvent('download');
  await page.getByRole('button',{name:'导出备份'}).click();
  const saved = await download;
  await tab(guest,'数据与备份');
  await guest.locator('#restore').setInputFiles(await saved.path());
  await status(guest,'已导入 2 份记录');
  await guest.locator('#restore').setInputFiles(await saved.path());
  await status(guest,'已导入 0 份记录');
  await guest.locator('#restore').setInputFiles({name:'bad.ppstudio',mimeType:'application/octet-stream',buffer:Buffer.from('corrupt')});
  await status(guest,'备份格式无效');
  await tab(guest,'私人题库');
  await guest.getByRole('button',{name:'笔记与草稿'}).first().click();
  assert.equal(await guest.getByLabel('学习笔记').inputValue(),notes);
  guest.once('dialog',dialog=>dialog.accept());
  await guest.getByRole('button',{name:'移除本地副本'}).click();
  await status(guest,'已移除本地副本');
  assert.equal(await guest.getByRole('button',{name:'笔记与草稿'}).count(),1);

  await tab(page,'我的 AI');
  await page.getByLabel('本机端口').fill(runtimePort);
  await page.getByRole('button',{name:'连接并读取模型'}).click();
  await page.locator('#ai-state').filter({hasText:'已连接'}).waitFor();
  assert.equal(await page.getByLabel('模型').locator('option').count(),1);
  await page.getByLabel('你想发送的内容').fill(prompt);
  await page.getByRole('button',{name:'发送给本机模型'}).click();
  await page.locator('#answer').filter({hasText:'Mock local response'}).waitFor();
  await page.getByLabel('提供方').selectOption('lmstudio');
  await page.getByLabel('本机端口').fill(runtimePort);
  await page.getByRole('button',{name:'连接并读取模型'}).click();
  await status(page,'运行时拒绝授权');
  await page.getByLabel('本机运行时令牌（可选）').fill('fixture-runtime-token');
  await page.getByRole('button',{name:'连接并读取模型'}).click();
  await page.locator('#ai-state').filter({hasText:'已连接'}).waitFor();
  await page.getByRole('button',{name:'断开并清除'}).click();
  assert.equal(await page.getByLabel('本机运行时令牌（可选）').inputValue(),'');
  assert.equal(await page.getByRole('button',{name:'发送给本机模型'}).isDisabled(),true);

  await tab(guest,'共享题库');
  await guest.getByLabel('公开标题').fill('审核演示');
  await guest.getByLabel('选择用于分享的 PDF').setInputFiles(file('share.pdf','explicit public fixture'));
  await guest.getByLabel('投稿码').fill(submissionCode);
  await guest.getByRole('checkbox').check();
  await guest.getByRole('button',{name:'提交审核'}).click();
  await status(guest,'已提交');
  await tab(page,'共享题库');
  await page.getByText('暂无已发布题目。',{exact:true}).waitFor();
  await page.getByText('维护者审核',{exact:true}).click();
  await page.getByLabel('审核密钥').fill(moderationKey);
  await page.getByRole('button',{name:'读取待审核列表'}).click();
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'通过并发布'}).click();
  await status(page,'审核结果已保存');
  await guest.getByRole('button',{name:'刷新题库'}).click();
  await guest.getByRole('button',{name:'保存到私人题库'}).click();
  await status(guest,'已下载并保存在当前设备');
  page.once('dialog',dialog=>dialog.accept());
  await page.getByRole('button',{name:'下架'}).click();
  await status(page,'审核结果已保存');
  await guest.getByRole('button',{name:'刷新题库'}).click();
  await guest.getByText('暂无已发布题目。',{exact:true}).waitFor();

  assert.equal(requests.some(request=>request.url.startsWith(origin+'/api/')),false);
  assert.equal(requests.some(request=>request.body?.includes(notes) || request.body?.includes('Fixture private draft')),false);
  assert.deepEqual(requests.filter(request=>request.body?.includes(prompt)).map(request=>request.url),[`http://127.0.0.1:${runtimePort}/api/generate`]);
  assert.equal(requests.some(request=>request.url.startsWith(origin) && request.auth?.includes('fixture-runtime-token')),false);
  assert.equal(requests.filter(request=>request.url===origin+'/share/submissions').length,1);
  await page.waitForFunction(() => Boolean(navigator.serviceWorker.controller));
  await first.setOffline(true);
  await page.reload();
  await page.getByText('2 份 PDF',{exact:true}).waitFor();
  await page.getByRole('button',{name:'笔记与草稿'}).first().click();
  assert.equal(await page.getByLabel('学习笔记').inputValue(),notes);
  await first.setOffline(false);
  console.log(`PASS: 5 widths, keyboard, local PDFs/QP+MS, notes, profiles, backup/restore, corrupt backup, deletion, AI wire isolation, shared moderation, offline reload (${requests.length} observed requests)`);
} finally { await browser.close(); }
