const languageKey = 'pastpaper-classroom-language';
const themeKey = 'pastpaper-classroom-theme';
const savedLanguage = localStorage.getItem(languageKey);
export let language = ['en','zh-CN'].includes(savedLanguage) ? savedLanguage :
  navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
const bindings = new WeakMap();

export function localCopy(node, render, attribute = 'textContent') {
  const apply = () => {
    const value = render();
    if (attribute === 'textContent') node.textContent = value;
    else node.setAttribute(attribute, value);
  };
  const updates = bindings.get(node) || new Map();
  updates.set(attribute, apply);
  bindings.set(node, updates);
  apply();
  return node;
}

export function t(text, ...values) {
  const output = language === 'en' ? words[text] || text : text;
  return values.length ? output.replace(/\{(\d+)\}/g, (_,index) => String(values[Number(index)] ?? '')) : output;
}

export function errorCopy(value) {
  if (!value) return t('操作未完成。');
  const translation = t(value);
  return language === 'en' && /\p{Script=Han}/u.test(translation) ? 'Operation incomplete. Check your settings and try again.' : translation;
}

export function applyPreferences(){
  const root=document.documentElement;
  const lang=document.getElementById('device-language');
  const theme=document.getElementById('device-theme');
  const preferred=localStorage.getItem(themeKey);
  const appearance=['light','dark','system'].includes(preferred)?preferred:'system';
  root.lang=language;root.dataset.theme=appearance;
  lang.value=language;theme.value=appearance;
  lang.onchange=()=>{
    language=lang.value;
    localStorage.setItem(languageKey,language);
    root.lang=language;
    const walker=document.createTreeWalker(root,NodeFilter.SHOW_ELEMENT|NodeFilter.SHOW_TEXT);
    while(walker.nextNode()){
      for(const update of bindings.get(walker.currentNode)?.values()||[])update();
    }
  };
  theme.onchange=()=>{localStorage.setItem(themeKey,theme.value);root.dataset.theme=theme.value;};
  const walker=document.createTreeWalker(document.documentElement,NodeFilter.SHOW_TEXT);
  while(walker.nextNode()){
    const node=walker.currentNode;
    const value=node.textContent, key=value.trim();
    if(words[key])localCopy(node,()=>value.replace(key,t(key)));
  }
  for(const node of document.querySelectorAll('[aria-label],[placeholder],[title]')){
    for(const attribute of ['aria-label','placeholder','title']){
      const value=node.getAttribute(attribute);
      if(value&&words[value])localCopy(node,()=>t(value),attribute);
    }
  }
}
